#!/usr/bin/env python3
"""Writes manifests/voyager_e4.txt from a game folder: one line per file the
port uses, "sha256 size path" for the programs and small data, "- size path"
for the large data (segments, textures, models, ...), whose presence and size
are checked but which are not hashed at launch.

    python3 -I tools/make_manifests.py "<game folder>" manifests/voyager_e4.txt
"""
import hashlib, os, sys

HASHED = ['trek', 'stvserv', 'stvsnd', 'depthtable.tab', 'stv/arom/cpuarom.hex',
          'stv/arom/voyager0.bin', 'stv/arom/voyager1.bin', 'stv/arom/voyager2.bin', 'stv/arom/voyager3.bin']
SIZED_DIRS = ['stv/anims', 'stv/behaviors', 'stv/models', 'stv/segments', 'stv/textures']
SKIP_SUFFIX = ('.old', '.new', '.prev')


def main():
    root, out = sys.argv[1], sys.argv[2]
    lines = []
    for rel in HASHED:
        data = open(os.path.join(root, rel), 'rb').read()
        lines.append('%s %d %s' % (hashlib.sha256(data).hexdigest(), len(data), rel))
    for d in SIZED_DIRS:
        for name in sorted(os.listdir(os.path.join(root, d))):
            if name.endswith(SKIP_SUFFIX):
                continue
            p = os.path.join(root, d, name)
            if os.path.isfile(p):
                lines.append('- %d %s/%s' % (os.path.getsize(p), d, name))
    with open(out, 'w') as f:
        f.write('# Star Trek: Voyager arcade, build e4 (trek = trek.e4). Generated by tools/make_manifests.py.\n')
        f.write('\n'.join(lines) + '\n')
    print('%d entries' % len(lines))


main()
